/**
 * Source lists: which sites a cite should raise an eyebrow about.
 *
 * Defaults are CATEGORIES of source that debate norms treat as weak
 * (user-generated, self-published, AI output, satire, study-help sites,
 * links that aren't the source at all). No journal, publisher or outlet
 * is named as untrustworthy by default — that is the user's call, made
 * in the plugin settings (one domain per line, optional `# note`).
 */
import type { Severity } from './findings.js';

export interface SourceRule {
  /** Matches the host and its subdomains (`medium.com` matches
   *  `x.medium.com`). A path prefix narrows it (`google.com/search`). */
  domain: string;
  severity: Severity;
  /** Completes "Source: …". */
  why: string;
}

const r = (severity: Severity, why: string, ...domains: string[]): SourceRule[] =>
  domains.map((domain) => ({ domain, severity, why }));

