/** Parse a settings list: `domain[/path]  # note` per line. */
export function parseDomainList(text: string, severity: Severity, defaultWhy: string): SourceRule[] {
  const out: SourceRule[] = [];
  for (const line of text.split(/\r?\n/)) {
    const [rawDomain, ...note] = line.split('#');
    const domain = (rawDomain ?? '')
      .trim()
      .toLowerCase()
      .replace(/^https?:\/\//, '')
      .replace(/^www\./, '')
      .replace(/\/+$/, '');
    if (!domain || /\s/.test(domain)) continue;
    out.push({ domain, severity, why: note.join('#').trim() || defaultWhy });
  }
  return out;
}

/** Does `rule` cover this URL (host + path)? */
export function ruleMatches(rule: SourceRule, host: string, path: string): boolean {
  const [ruleHost, ...rest] = rule.domain.split('/');
  if (!ruleHost) return false;
  if (host !== ruleHost && !host.endsWith(`.${ruleHost}`)) return false;
  if (rest.length === 0) return true;
  return `${path.replace(/^\/+/, '')}/`.startsWith(`${rest.join('/')}/`) || path.replace(/^\/+/, '') === rest.join('/');
}

/** The first rule that covers `host`+`path`; `trusted` wins over all. */
export function classifySource(
  host: string,
  path: string,
  rules: readonly SourceRule[],
  trusted: readonly SourceRule[],
): SourceRule | null {
  if (trusted.some((t) => ruleMatches(t, host, path))) return null;
  return rules.find((rule) => ruleMatches(rule, host, path)) ?? null;
}
