#!/usr/bin/env node
/**
 * Apply a brand profile (brand/<id>/) to the build: copy its generated icons
 * to where electron-builder and Vite look for them, and write the brand
 * constants the app code reads (src/brand-build.ts for the renderer,
 * apps/desktop/src/brand-build.ts for the main process).
 *
 *   node scripts/apply-brand.mjs            # BRAND env, default cardreflex
 *   BRAND=cardmirror node scripts/apply-brand.mjs
 *
 * Mirrors apps/desktop/scripts/inject-lite-build.cjs: the committed copies
 * of every output equal the DEFAULT profile, so a default build leaves the
 * working tree clean. Files are only rewritten when their bytes differ.
 * Icons are rendered separately (scripts/gen-brand-assets.py) and
 * committed under brand/<id>/generated/, so this step needs only Node.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

export const DEFAULT_BRAND = 'cardreflex';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** brand.json for `id` (throws on an unknown profile). */
export function loadBrand(id = process.env.BRAND || DEFAULT_BRAND) {
  const file = join(ROOT, 'brand', id, 'brand.json');
  if (!existsSync(file)) throw new Error(`apply-brand: unknown brand "${id}" (no ${relative(ROOT, file)})`);
  return JSON.parse(readFileSync(file, 'utf8'));
}

let changed = 0;
function writeIfChanged(path, bytes) {
  const buf = Buffer.isBuffer(bytes) ? bytes : Buffer.from(bytes, 'utf8');
  if (existsSync(path) && readFileSync(path).equals(buf)) return;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, buf);
  changed++;
}

/** Copy every file under `from` into `to`; with `exact`, also delete files
 *  in `to` that the profile doesn't have (so switching profiles never
 *  leaves a previous brand's tile behind). */
function copyTree(from, to, { exact = false } = {}) {
  if (!existsSync(from)) {
    if (exact && existsSync(to)) {
      rmSync(to, { recursive: true });
      changed++;
    }
    return;
  }
  const names = new Set();
  for (const name of readdirSync(from)) {
    names.add(name);
    const src = join(from, name);
    if (statSync(src).isDirectory()) copyTree(src, join(to, name), { exact });
    else writeIfChanged(join(to, name), readFileSync(src));
  }
  if (exact && existsSync(to)) {
    for (const name of readdirSync(to)) {
      if (!names.has(name)) {
        rmSync(join(to, name), { recursive: true });
        changed++;
      }
    }
  }
}

function tsModule(brand, extra = '') {
  const fields = {
    id: brand.id,
    productName: brand.productName,
    liteName: brand.liteName,
    docTypeName: brand.docTypeName,
    lineage: brand.lineage,
    renamedFrom: brand.renamedFrom,
  };
  return (
    '// AUTO-GENERATED by scripts/apply-brand.mjs from brand/' +
    brand.id +
    '/brand.json — do not edit.\n' +
    '// Committed content = the default profile; see brand/README.md.\n' +
    `export const BRAND = ${JSON.stringify(fields, null, 2)} as const;\n` +
    extra
  );
}

export function applyBrand(id = process.env.BRAND || DEFAULT_BRAND) {
  const brand = loadBrand(id);
  const gen = join(ROOT, 'brand', brand.id, 'generated');
  const build = join(ROOT, 'apps', 'desktop', 'build');
  changed = 0;

  copyTree(join(gen, 'desktop'), build);
  copyTree(join(gen, 'appx'), join(build, 'appx'), { exact: true });
  copyTree(join(gen, 'public'), join(ROOT, 'public'));

  const mark = readFileSync(join(gen, 'file-mark-48.png')).toString('base64');
  writeIfChanged(
    join(ROOT, 'src', 'brand-build.ts'),
    tsModule(
      brand,
      '\n/** The status-bar file mark (48 px PNG): drag handle and drag image. */\n' +
        `export const FILE_MARK_DATA_URL =\n  'data:image/png;base64,${mark}';\n`,
    ),
  );
  writeIfChanged(join(ROOT, 'apps', 'desktop', 'src', 'brand-build.ts'), tsModule(brand));
  console.log(`[apply-brand] ${brand.id}: ${changed ? `${changed} file(s) updated` : 'already applied'}`);
  return brand;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  applyBrand();
}
